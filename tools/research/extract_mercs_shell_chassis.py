#!/usr/bin/env python3
"""Extract DOS-owned-mech launch names and cross-check the retail Windows table."""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def elf_reader(data):
    phoff = struct.unpack_from('<I', data, 28)[0]
    phnum = struct.unpack_from('<H', data, 44)[0]
    segments = [struct.unpack_from('<8I', data, phoff + 32*i) for i in range(phnum)]
    def read(address, size):
        for _, offset, va, _, length, _, _, _ in segments:
            if va <= address and address + size <= va + length:
                return data[offset + address - va:offset + address - va + size]
        raise ValueError(hex(address))
    return read


def main():
    import pefile
    p = argparse.ArgumentParser()
    p.add_argument('--dos-shell-elf', required=True)
    p.add_argument('--windows-shell', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--header', required=True)
    a = p.parse_args()
    dos = Path(a.dos_shell_elf).read_bytes()
    win = Path(a.windows_shell).read_bytes()
    assert hashlib.sha256(dos).hexdigest() == 'cb355cf34234aa5b209b85c2c1e8e5bd1f3f4b2a2541da03a170e019c87f526c'
    assert hashlib.sha256(win).hexdigest() == 'f59de3cce3e7ec16cc9dc1d539cf19d2b8d1673f107a3b0d8f280c069d2d1bf0'
    rd = elf_reader(dos)
    pe = pefile.PE(data=win)
    def rw(address, size):
        off = pe.get_offset_from_rva(address - pe.OPTIONAL_HEADER.ImageBase)
        return win[off:off+size]
    def string(reader, pointer):
        return reader(pointer, 80).split(b'\0', 1)[0].decode('ascii')
    rows = []
    for i in range(71):
        outputs = []
        for read, address in [(rd, 0xb8bf0 + i*37), (rw, 0x10083d8c + i*40)]:
            b = read(address, 29)
            fields = [string(read, struct.unpack_from('<I', b, off)[0]) for off in (0, 4, 8)]
            outputs.append(dict(prefix=fields[0].upper(), skeleton=fields[1][:8].upper(),
                                name=fields[2], kind=b[28]))
        assert outputs[0] == outputs[1], (i, outputs)
        rows.append(outputs[0])
    result = dict(dos_sha256=hashlib.sha256(dos).hexdigest(), windows_sha256=hashlib.sha256(win).hexdigest(),
                  dos_table='0x000b8bf0', dos_stride=37, windows_table='0x10083d8c', windows_stride=40,
                  all_fields_match=True, rows=rows)
    Path(a.output).write_text(json.dumps(result, indent=2)+'\n')
    text = ['/* Original DOS shell launch table, cross-checked against retail Windows.',
            ' * Generated by tools/research/extract_mercs_shell_chassis.py. */',
            '#ifndef MERCS_SHELL_CHASSIS_H', '#define MERCS_SHELL_CHASSIS_H',
            'static const struct { const char *prefix, *skeleton, *name; int kind; } mercs_shell_chassis[] = {']
    text += ['    {%s, %s, %s, %d},' % (json.dumps(x['prefix']),json.dumps(x['skeleton']),json.dumps(x['name']),x['kind']) for x in rows]
    text += ['};', '#endif', '']
    Path(a.header).write_text('\n'.join(text))
    print(json.dumps(dict(rows=len(rows), original_tables_agree=True)))


if __name__ == '__main__':
    main()
