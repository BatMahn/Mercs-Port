#!/usr/bin/env python3
"""Recover the supplied retail Mercs effect tables; standard library only.

This reads original files without running them. DOS input is the analysis ELF
made by tools/le2elf.py. The JSON retains all eleven original words, including
fields whose full consumers remain outside this bounded port correction.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct


def pe_offset(data, address):
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        raise ValueError('Not a PE image')
    count = struct.unpack_from('<H', data, pe + 6)[0]
    optional_size = struct.unpack_from('<H', data, pe + 20)[0]
    base = struct.unpack_from('<I', data, pe + 52)[0]
    for i in range(count):
        at = pe + 24 + optional_size + i * 40
        _, rva, size, offset = struct.unpack_from('<4I', data, at + 8)
        if base + rva <= address < base + rva + size:
            return offset + address - base - rva
    raise ValueError('Address is not file backed')


def elf_offset(data, address):
    if data[:7] != b'\x7fELF\x01\x01\x01':
        raise ValueError('Expected converted ELF32 little endian image')
    ph = struct.unpack_from('<I', data, 28)[0]
    count = struct.unpack_from('<H', data, 44)[0]
    stride = struct.unpack_from('<H', data, 42)[0]
    for i in range(count):
        kind, off, va, _, size, _, _, _ = struct.unpack_from('<8I', data, ph + i * stride)
        if kind == 1 and va <= address < va + size:
            return off + address - va
    raise ValueError('Address is not file backed')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--windows', type=Path, required=True)
    p.add_argument('--dos-elf', type=Path, required=True)
    p.add_argument('--foundation-fx', type=Path, required=True)
    p.add_argument('--json', type=Path, required=True)
    p.add_argument('--header', type=Path)
    a = p.parse_args()
    win, dos = a.windows.read_bytes(), a.dos_elf.read_bytes()
    expected = 'bc375715180221e42fa5970ef966854fc691f076762fb9c71df846b04dfb69ef'
    if hashlib.sha256(win).hexdigest() != expected:
        raise ValueError('Unrecognized retail Windows engine; do not reuse these addresses')
    offsets = [pe_offset(win, 0x100a9670), elf_offset(dos, 0xbe6dc)]
    rows = [[list(struct.unpack_from('<11i', data, offset + i * 44)) for i in range(36)]
            for data, offset in zip((win, dos), offsets)]
    if any(w[1:] != d[1:] for w, d in zip(*rows)):
        raise ValueError('DOS and Windows non-timer fields disagree')
    old_text = a.foundation_fx.read_text()
    old_table = old_text.split('static const int TABLE', 1)[1].split('};', 1)[0]
    old = [list(map(int, m)) for m in re.findall(r'\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}', old_table)]
    if len(old) != 32:
        raise ValueError('Expected the supplied mature MW2 32-row effect table')
    report = {
        'scope': 'Original data and selected original consumers; not complete special-weapon parity',
        'windows_sha256': hashlib.sha256(win).hexdigest(),
        'dos_elf_sha256': hashlib.sha256(dos).hexdigest(),
        'foundation_fx_sha256': hashlib.sha256(a.foundation_fx.read_bytes()).hexdigest(),
        'windows_table_va': '0x100a9670', 'dos_table_va': '0xbe6dc',
        'entry_stride_bytes': 44, 'entry_count': 36,
        'fields': ['duration', 'camera_effect', 'sound', 'sound_chance', 'light',
                   'needs_object', 'area_enabled', 'unknown_1c', 'damage_q16_per_tick',
                   'heat_q16_per_tick', 'flags'],
        'windows': rows[0], 'dos': rows[1], 'foundation_duration_sound_light': old,
        'changed_sound_types': [i for i, row in enumerate(old) if row[1] != rows[0][i][2]],
        'changed_windows_duration_types': [i for i, row in enumerate(old) if row[0] != rows[0][i][0]],
        'new_types': list(range(32, 36)),
    }
    a.json.parent.mkdir(parents=True, exist_ok=True)
    a.json.write_text(json.dumps(report, indent=2) + '\n')
    if a.header:
        text = ['/* Generated by tools/research/extract_mercs_effects.py from original retail tables.',
                ' * Windows 0x100a9670; DOS 0xbe6dc; 36 records of 44 bytes.',
                ' * All fields after duration agree between the supplied DOS and Windows engines.',
                ' * See tests/fixtures/MERCS_ENGINE_EFFECTS_AUDIT.md for consumer limits. */',
                '#ifndef MERCS_FX_DATA_H', '#define MERCS_FX_DATA_H',
                'static const int mercs_fx_windows[36][11] = {']
        text += ['    {' + ', '.join(map(str, r)) + '}, /* %d */' % i for i, r in enumerate(rows[0])]
        text += ['};', 'static const int mercs_fx_dos_duration[36] = {',
                 '    ' + ', '.join(str(r[0]) for r in rows[1]), '};', '#endif', '']
        a.header.write_text('\n'.join(text))
    print('Recovered 36 DOS/Windows effect rows; %d inherited sound IDs differ' % len(report['changed_sound_types']))


if __name__ == '__main__':
    main()
