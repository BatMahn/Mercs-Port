#!/usr/bin/env python3
"""Check bounded Mercenaries shell/career behavior using private outputs.

Includes original-art/audio/text, cold-start isolation, save interchange,
economy, Mech Lab and career transactions. Real shell input sequences and long
mission-child runs retain their separate regression scripts. Optional original
AeroTech/economy fixtures are generated by the documented execution probes;
the original programs and extracted records are not bundled with the source.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", type=Path, required=True)
    parser.add_argument("--aerotech-fixtures", type=Path,
                        help="Private output of tests/fixtures/verify_original_aerotech.py")
    parser.add_argument("--economy-fixtures", type=Path,
                        help="Private output of tests/fixtures/verify_original_economy.py")
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]
    game = args.game.resolve()
    archive = game / "cd/MERCS/MW2.PRJ"
    database = game / "cd/MERCS/DATABASE.MW2"
    movie = game / "cd/SMK/MINTRO.SMK"
    for path in (archive, database, movie, game / "cd/MERCS/MW2SHELL.EXE",
                 game / "cd/RMG/MIS0SCN1.BWD"):
        if not path.is_file():
            parser.error(f"Required original fixture is missing: {path}")
    for path in (args.aerotech_fixtures, args.economy_fixtures):
        if path is not None and not path.is_dir():
            parser.error(f"Required private original fixtures are missing: {path}")

    env = {k: v for k, v in os.environ.items() if not k.startswith(("MERCS_", "MW2_"))}
    env["SDL_AUDIO_DRIVER"] = "dummy"
    if sys.platform.startswith("linux"):
        env.setdefault("SDL_VIDEO_DRIVER", "offscreen")
        env.setdefault("LIBGL_ALWAYS_SOFTWARE", "1")
    checks = 0
    skipped = []

    def run(name, *arguments, expected=0, timeout=90):
        nonlocal checks
        executable = project / (name + (".exe" if os.name == "nt" else ""))
        if not executable.is_file():
            raise RuntimeError(f"Missing test executable {executable.name}; build it with make {name}")
        print(f"RUN: {name}", flush=True)
        result = subprocess.run([str(executable), *(str(v) for v in arguments)],
                                cwd=project, env=env, text=True, errors="replace",
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                timeout=timeout)
        if result.returncode != expected:
            raise RuntimeError(f"{name}: exit {result.returncode}, expected {expected}\n{result.stdout}")
        print(result.stdout.rstrip(), flush=True)
        checks += 1

    with tempfile.TemporaryDirectory(prefix="mercs-shell-check-") as temporary:
        output = Path(temporary)

        def private(name):
            path = output / name
            path.mkdir()
            return path

        env["MERCS_CONFIG"] = str(output / "port.cfg")
        env["MESA_SHADER_CACHE_DIR"] = str(private("shader-cache"))
        run("test_mercs_shell_data", archive, private("shell-data"))
        run("test_mercs_shell_sim", archive, private("shell-sim"))
        run("test_mercs_video", movie, private("video"))
        run("test_mercs_startup", game, private("startup"))
        run("test_mercs_text", archive, database)
        run("test_mercs_campaign_tail", archive)

        # These bounded core fixtures operate on private/synthetic documents;
        # actual Save/Load, Lab, market and IA SDL input gates remain separate.
        for name in ("save", "debrief", "debrief_view", "repair", "repair_view",
                     "statistics", "economy", "mechlab"):
            run("test_mercs_" + name)
        run("test_mercs_campaign", archive, private("campaign"))
        run("test_mercs_interchange", archive, private("interchange"))
        run("test_mercs_scores", private("scores"))
        run("test_mercs_debrief_assets", archive, database)
        run("test_mercs_viewport")
        run("test_mercs_art", database, game / "cd")
        run("test_mercs_shell_audio", database)
        run("test_mercs_dialog")
        run("test_mercs_gamemenu")
        run("test_mercs_panels", game / "cd/MERCS/MW2SHELL.EXE")

        if args.aerotech_fixtures:
            fixture = args.aerotech_fixtures.resolve()
            for stock in ("ARO00STD", "ARO01STD", "ARO02STD"):
                for suffix in ("raw", "record", "deploy"):
                    if not (fixture / f"{stock}.{suffix}").is_file():
                        raise RuntimeError(f"Missing original AeroTech fixture: {stock}.{suffix}")
            run("test_mercs_aerotech", fixture)
        else:
            skipped.append("original AeroTech full-record/deployment comparisons (supply --aerotech-fixtures)")

        if args.economy_fixtures:
            fixture = args.economy_fixtures.resolve()
            report = json.loads((fixture / "original-economy.json").read_text())
            cases = report.get("cases", [])
            if not cases:
                raise RuntimeError("Original economy fixture report has no transaction cases")
            actual_dir = private("economy-original")
            for index, case in enumerate(cases):
                # Only a basename can select a file inside the supplied
                # fixture directory. Actual native outputs stay temporary.
                name = case["name"]
                if not name or Path(name).name != name or name in (".", ".."):
                    raise RuntimeError("Invalid original economy fixture name")
                source = fixture / (name + ".input")
                expected = fixture / (name + ".expected")
                for path, key in ((source, "input_sha256"), (expected, "expected_sha256")):
                    if hashlib.sha256(path.read_bytes()).hexdigest() != case[key]:
                        raise RuntimeError("Original economy fixture hash differs: " + str(path))
                actual = actual_dir / f"case-{index:03d}.actual"
                run("test_mercs_economy_original", case["kind"], case["buy"], case["index"],
                    source, actual, expected=3 if case.get("dialogs") else 0)
                if actual.read_bytes() != expected.read_bytes():
                    raise RuntimeError("Complete native/original economy documents differ: " + name)
            print(f"PASS: {len(cases)} original economy complete-document comparisons", flush=True)
        else:
            skipped.append("executed-original economy complete-save comparisons (supply --economy-fixtures)")

    for reason in skipped:
        print("SKIP: " + reason, flush=True)
    print(f"PASS: {checks} bounded Mercenaries shell/career checks; "
          f"{len(skipped)} optional external-fixture groups skipped", flush=True)


if __name__ == "__main__":
    main()
