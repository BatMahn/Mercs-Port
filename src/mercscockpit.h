#ifndef MERCS_COCKPIT_H
#define MERCS_COCKPIT_H

#include "mech3d.h"

/* A reusable, visible copy of a posed representation-4 model. Only the part,
 * object and polygon arrays are owned here; vertices and other resources are
 * borrowed from the source. Zero-initialize before the first update. Never
 * pass model to mech3d_free, and keep the source alive until after drawing. */
typedef struct {
    mech3d model;
    struct mercs_cockpit_part_cache *cache;
    int capacity;
    int head_node;               /* first class-0xa0 node, or -1 */
    int pit_parts;               /* visible parts in that node's subtree */
} mercs_cockpit_layer;

/* All parts and all objects are retained, with back-facing polygons removed.
 * objtype keeps the representation's runtime class. dos_pit independently
 * marks membership in the selected head subtree: a class-0x100 arm/visor may
 * belong to it. The original draws ordinary class!=0xa0 objects in the world
 * pass, then traverses the head subtree again with the cockpit near plane.
 * The result remains valid until the next update/free. Returns 0, or -1 on
 * invalid input/allocation failure (leaving model.part_count zero). */
int mercs_cockpit_update(mercs_cockpit_layer *layer, const mech3d *posed,
                        const float eye[3]);
/* Accelerated views opt into fractional solved translations on these drawing
 * copies, before testing their faces. Pass zero for the original integer DOS
 * path. All repr4 pieces share the choice, including those also drawn in the
 * ordinary world pass. The three-argument function above preserves the
 * integer behavior for existing callers; neither version edits posed. */
int mercs_cockpit_update_render(mercs_cockpit_layer *layer, const mech3d *posed,
                               const float eye[3], int fractional_translation);
void mercs_cockpit_free(mercs_cockpit_layer *layer);

/* Mercs DOS 0x45988 / 0x48003: polygon plane normal in signed 2.29 units.
 * Larger polygons use the original longest-edge/area-bit selection, rather
 * than assuming the first three vertices define the plane. Return -1 for an
 * invalid polygon. Exposed for the original-execution regression fixtures. */
int mercs_cockpit_dos_normal(const wtb_object *object, const wtb_poly *polygon,
                            int32_t normal[3]);
/* Mercs DOS 0x4d379's strict facing test, using the selected draw translation
 * (the original integer placement unless a cockpit layer activates it).
 * Extended models use their stored normals; Titanium's DOS-layout models use
 * the normals generated by their own loader. Points/lines bypass the plane
 * test, as in the original. Invalid polygons are not visible. */
int mercs_cockpit_face_visible(const mech3d_part *part, const wtb_object *object,
                              const wtb_poly *polygon, const float eye[3]);

#endif
